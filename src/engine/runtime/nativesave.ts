/**
 * Emuera's own save files (EraBinaryDataWriter / EraBinaryDataReader, format 1808) <-> the web snapshot.
 *
 * Written from the C# source, not from sample files (none were available): treat byte-level compatibility as unverified until a real
 * save from the original has been read by `fromNativeSlot` and one of ours has been loaded by the original.
 *
 *   toNativeSlot(vm, rec)      web slot { info, data }       -> bytes of saveNN.sav (SystemSaveInBinary format)
 *   toNativeGlobal(vm, rec)    web global { data }           -> bytes of global.sav
 *   fromNative(vm, bytes)      saveNN.sav / global.sav       -> { kind, info, code, ver, data }  (async: a gzip-compressed file needs DecompressionStream)
 *
 * What is written (VariableEvaluator.SaveToStreamBinary / SaveGlobal): header, file type, game code, game version, header text,
 * character count, one block per character, the non-character saved variables, EOF, then the EM block (maps, xml, data tables), EOF.
 * Variables are name-keyed and the original's loader matches them by name, so the order only matters for byte-for-byte equality;
 * it follows the original's `varTokenDic` order (reference/save-vars.json, generated by tools/extract-save-vars.ts), then user #DIM variables.
 */
