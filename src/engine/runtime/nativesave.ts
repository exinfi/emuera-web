/**
 * JSON.stringify for comparing records. Integers are written as `<digits>n` whether they are numbers or BigInt: a saved value above 2^53 can sit in a record as a plain number
 * (1e16 is exact in a double) while the native read always gives BigInt for it, and the two are the same value. An int array never mixes with a string array, so `5n` cannot collide.
 */
const J = (x: unknown) =>
  JSON.stringify(x, (_k, v) =>
    typeof v === 'bigint'
      ? v.toString() + 'n'
      : typeof v === 'number' && Number.isInteger(v)
        ? BigInt(v).toString() + 'n'
        : v,
  );
const sortJ = (l: unknown[]) => l.map((x) => J(x)).sort();
/** our records are sparse and a native read is full, so compare with every all-default variable dropped */
export function normRec(vm: VM, kind: 'slot' | 'global', data: string): unknown {
  const d = parseSaveText(data) as any;
  // only what the native format stores is compared: builtin saved variables, user #DIM SAVEDATA, user GLOBAL (a CHARADATA variable without SAVEDATA is not saved by the original either)
  const uv = userVars(vm);
  const stat = new Set<string>([
    ...SAVED.filter((v) => !v.chara && (kind === 'global') === v.global).map((v) => v.name.toUpperCase()),
    ...uv
      .filter((u) => !u.isChara && (kind === 'global' ? u.isGlobal : u.isSave && !u.isGlobal))
      .map((u) => u.name.toUpperCase()),
  ]);
  const chara = new Set<string>([
    ...SAVED.filter((v) => v.chara).map((v) => v.name.toUpperCase()),
    ...uv.filter((u) => u.isChara && u.isSave).map((u) => u.name.toUpperCase()),
  ]);
  const keep = (l: [string, unknown[]][], set: Set<string>) =>
    sortJ(l.filter(([k, a]) => set.has(k.toUpperCase()) && nonDefault(a)));
  if (kind === 'global') return keep(d, stat);
  return {
    g: keep(d.global ?? [], stat),
    c: (d.charas ?? []).map((c: any) => ({ v: keep(c.vars, chara) })),
    m: sortJ(d.maps ?? []),
    t: sortJ((d.dts ?? []).map(([k]: [string]) => k)),
  };
}
/** where two normalised records first differ (for the self-check message): variable names only on one side, then the first differing element of the first variable that differs */
function describeDiff(orig: unknown, back: unknown): string {
  const show = (v: unknown) => {
    const s = (J(v) ?? 'undefined').replace(/"(-?\d+)n"/g, '$1'); // integers show without the comparison marker
    return s.length > 60 ? s.slice(0, 57) + '...' : s;
  };
  const firstCell = (a: unknown, b: unknown, path: string): string | null => {
    if (Array.isArray(a) && Array.isArray(b)) {
      if (a.length !== b.length) return `${path} length ${a.length} vs ${b.length}`;
      for (let i = 0; i < a.length; i++) {
        const r = firstCell(a[i], b[i], `${path}[${i}]`);
        if (r) return r;
      }
      return null;
    }
    return J(a) === J(b) ? null : `${path} original ${show(a)} read back ${show(b)}`;
  };
  const vars = (l: unknown): Map<string, unknown> => {
    const m = new Map<string, unknown>();
    if (Array.isArray(l))
      for (const s of l) {
        const [k, a] = JSON.parse(String(s));
        m.set(String(k), a);
      }
    return m;
  };
  const cmpVars = (a: unknown, b: unknown, where: string): string | null => {
    const A = vars(a),
      B = vars(b);
    const only = (x: Map<string, unknown>, y: Map<string, unknown>) => [...x.keys()].filter((k) => !y.has(k));
    const oa = only(A, B),
      ob = only(B, A);
    if (oa.length || ob.length)
      return `${where}: only in the original: ${oa.slice(0, 5).join(', ') || '-'}; only after read-back: ${ob.slice(0, 5).join(', ') || '-'}`;
    for (const [k, v] of A) {
      const r = firstCell(v, B.get(k), k);
      if (r) return `${where}: ${r}`;
    }
    return null;
  };
  const o = orig as any,
    b = back as any;
  if (Array.isArray(o)) return cmpVars(o, b, 'global') ?? 'no difference found by name';
  const g = cmpVars(o.g, b.g, 'static variables');
  if (g) return g;
  if (o.c.length !== b.c.length) return `character count ${o.c.length} vs ${b.c.length}`;
  for (let i = 0; i < o.c.length; i++) {
    const c = cmpVars(o.c[i].v, b.c[i].v, `character ${i}`);
    if (c) return c;
  }
  if (J(o.m) !== J(b.m)) return 'map data differs';
  if (J(o.t) !== J(b.t)) return 'data table list differs';
  return 'no difference found by name';
}
/** read our own output back and compare it with the record it was made from; returns a problem description or null when they match */
export async function selfCheck(
  vm: VM,
  kind: 'slot' | 'global',
  rec: { data: string; info?: string },
  bytes: Uint8Array,
): Promise<string | null> {
  try {
    const r = await fromNative(vm, bytes);
    if (r.kind !== kind) return 'file type changed';
    const back = normRec(vm, kind, r.data);
    const orig = normRec(vm, kind, rec.data);
    return J(back) === J(orig)
      ? null
      : 'the converted file does not read back to the same data: ' + describeDiff(orig, back);
  } catch (e: any) {
    return 'the converted file cannot be read back: ' + (e?.message ?? e);
  }
}
