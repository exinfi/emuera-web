// ------------------------------------------------------------------------------------------------ .NET BinaryWriter / BinaryReader (Encoding.Unicode)
class BW {
  private b = new Uint8Array(1 << 16);
  private dv = new DataView(this.b.buffer);
  n = 0;
  private need(k: number) {
    if (this.n + k <= this.b.length) return;
    let c = this.b.length * 2;
    while (c < this.n + k) c *= 2;
    const nb = new Uint8Array(c);
    nb.set(this.b.subarray(0, this.n));
    this.b = nb;
    this.dv = new DataView(nb.buffer);
  }
  u8(v: number) {
    this.need(1);
    this.b[this.n++] = v;
  }
  i16(v: number) {
    this.need(2);
    this.dv.setInt16(this.n, v, true);
    this.n += 2;
  }
  i32(v: number) {
    this.need(4);
    this.dv.setInt32(this.n, v, true);
    this.n += 4;
  }
  u32(v: number) {
    this.need(4);
    this.dv.setUint32(this.n, v, true);
    this.n += 4;
  }
  i64(v: Int) {
    this.need(8);
    this.dv.setBigInt64(this.n, BigInt(v), true);
    this.n += 8;
  }
  raw(a: number[]) {
    for (const x of a) this.u8(x);
  }
  /** BinaryWriter.Write(string): 7-bit encoded byte count of the UTF-16LE text, then the text */
  str(s: string) {
    let len = s.length * 2;
    do {
      let x = len & 0x7f;
      len >>>= 7;
      if (len) x |= 0x80;
      this.u8(x);
    } while (len);
    this.need(s.length * 2);
    for (let i = 0; i < s.length; i++) {
      this.dv.setUint16(this.n, s.charCodeAt(i), true);
      this.n += 2;
    }
  }
  bytes() {
    return this.b.slice(0, this.n);
  }
}
class BR {
  p = 0;
  private dv: DataView;
  constructor(
    public b: Uint8Array,
    start = 0,
  ) {
    this.dv = new DataView(b.buffer, b.byteOffset, b.byteLength);
    this.p = start;
  }
  get eof() {
    return this.p >= this.b.length;
  }
  private chk(k: number) {
    if (this.p + k > this.b.length) throw new NativeSaveError('the save file ends too early');
  }
  u8() {
    this.chk(1);
    return this.b[this.p++];
  }
  i16() {
    this.chk(2);
    const v = this.dv.getInt16(this.p, true);
    this.p += 2;
    return v;
  }
  i32() {
    this.chk(4);
    const v = this.dv.getInt32(this.p, true);
    this.p += 4;
    return v;
  }
  u32() {
    this.chk(4);
    const v = this.dv.getUint32(this.p, true);
    this.p += 4;
    return v;
  }
  i64(): bigint {
    this.chk(8);
    const v = this.dv.getBigInt64(this.p, true);
    this.p += 8;
    return v;
  }
  str() {
    let len = 0,
      sh = 0,
      x: number;
    do {
      x = this.u8();
      len |= (x & 0x7f) << sh;
      sh += 7;
    } while (x & 0x80);
    this.chk(len);
    let s = '';
    for (let i = 0; i < len; i += 2) s += String.fromCharCode(this.dv.getUint16(this.p + i, true));
    this.p += len;
    return s;
  }
  /** EraBinaryDataReader1808.m_ReadInt */
  int(): Int {
    const b = this.u8();
    if (b <= E.Byte) return b;
    if (b === E.Int16) return this.i16();
    if (b === E.Int32) return this.i32();
    if (b === E.Int64) return norm(this.i64());
    throw new NativeSaveError('abnormal binary data in the save file');
  }
}
const norm = (v: bigint): Int => (v >= -9007199254740991n && v <= 9007199254740991n ? Number(v) : v);

// ------------------------------------------------------------------------------------------------ value writers (EraBinaryDataWriter.m_WriteInt, writeData)
function wInt(w: BW, v: Int) {
  if (typeof v === 'number' && Number.isSafeInteger(v)) {
    if (v >= 0 && v <= E.Byte) {
      w.u8(v);
      return;
    }
    if (v >= -32768 && v <= 32767) {
      w.u8(E.Int16);
      w.i16(v);
      return;
    }
    if (v >= -2147483648 && v <= 2147483647) {
      w.u8(E.Int32);
      w.i32(v);
      return;
    }
    w.u8(E.Int64);
    w.i64(v);
    return;
  }
  const b = BigInt(v);
  if (b >= -2147483648n && b <= 2147483647n) return wInt(w, Number(b));
  w.u8(E.Int64);
  w.i64(b);
}
/** the bytes the original writes for one integer (EraBinaryDataWriter.m_WriteInt); exported for the tests */
export function encodeInt(v: Int): Uint8Array {
  const w = new BW();
  wInt(w, v);
  return w.bytes();
}
const isZero = (v: Value | undefined) => v === 0 || v === 0n || v === undefined || v === null;
const isEmpty = (v: Value | undefined) => v === undefined || v === null || v === '';
type Item = (i: number) => boolean;
/** the zero-run encoding shared by int and string arrays; `put` writes a non-empty cell */
function wArr(w: BW, dims: number[], at: (i: number) => boolean /* true = zero/empty */, put: (i: number) => void) {
  for (const d of dims) w.i32(d);
  if (dims.length === 1) {
    let cz = 0;
    for (let x = 0; x < dims[0]; x++) {
      if (at(x)) cz++;
      else {
        if (cz > 0) {
          w.u8(E.Zero);
          wInt(w, cz);
          cz = 0;
        }
        put(x);
      }
    }
  } else if (dims.length === 2) {
    const [l0, l1] = dims;
    let cz = 0,
      caz = 0;
    for (let x = 0; x < l0; x++) {
      for (let y = 0; y < l1; y++) {
        const i = x * l1 + y;
        if (at(i)) cz++;
        else {
          if (caz > 0) {
            w.u8(E.ZeroA1);
            wInt(w, caz);
            caz = 0;
          }
          if (cz > 0) {
            w.u8(E.Zero);
            wInt(w, cz);
            cz = 0;
          }
          put(i);
        }
      }
      if (cz === l1) caz++;
      else w.u8(E.EoA1);
      cz = 0;
    }
  } else {
    const [l0, l1, l2] = dims;
    let cz = 0,
      caz = 0,
      caz2 = 0;
    for (let x = 0; x < l0; x++) {
      for (let y = 0; y < l1; y++) {
        for (let z = 0; z < l2; z++) {
          const i = (x * l1 + y) * l2 + z;
          if (at(i)) cz++;
          else {
            if (caz2 > 0) {
              w.u8(E.ZeroA2);
              wInt(w, caz2);
              caz2 = 0;
            }
            if (caz > 0) {
              w.u8(E.ZeroA1);
              wInt(w, caz);
              caz = 0;
            }
            if (cz > 0) {
              w.u8(E.Zero);
              wInt(w, cz);
              cz = 0;
            }
            put(i);
          }
        }
        if (cz === l2) caz++;
        else w.u8(E.EoA1);
        cz = 0;
      }
      if (caz === l1) caz2++;
      else w.u8(E.EoA2);
      caz = 0;
    }
  }
  w.u8(E.EoD);
}
/** WriteWithKey for one variable: rank 0 is a scalar record (character data only), higher ranks are arrays */
function wVar(w: BW, key: string, m: Meta, a: Arr | undefined) {
  const size = m.dims.reduce((p, q) => p * q, 1);
  const cell = (i: number): Value => (a && i < a.length ? a[i] : m.isStr ? '' : 0);
  const rank = m.rank;
  if (rank === 0) {
    w.u8(m.isStr ? DT.Str : DT.Int);
    w.str(key);
    if (m.isStr) w.str(String(cell(0) ?? ''));
    else wInt(w, cell(0) as Int);
    return;
  }
  const base = m.isStr ? DT.StrArray : DT.IntArray;
  w.u8(base + (rank - 1));
  w.str(key);
  void size;
  if (m.isStr)
    wArr(
      w,
      m.dims,
      (i) => isEmpty(cell(i)),
      (i) => {
        w.u8(E.String);
        w.str(String(cell(i)));
      },
    );
  else
    wArr(
      w,
      m.dims,
      (i) => isZero(cell(i)),
      (i) => wInt(w, cell(i) as Int),
    );
}

