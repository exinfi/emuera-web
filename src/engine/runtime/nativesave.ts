interface SnapChara {
  no: number;
  vars: [string, Arr][];
}
interface Snap {
  global: [string, Arr][];
  statics?: [string, Arr][];
  charas: SnapChara[];
  maps: [string, [string, string][]][];
  dts: [string, any][];
  xmls?: [string, string][];
}
const SAVED = saveVars.variables.filter((v) => v.saved);
const header = (w: BW, type: number, vm: VM, text: string) => {
  w.raw(HEADER);
  w.u32(VERSION);
  w.u32(0); // WriteHeader: header, 1808, data count 0
  w.u8(type);
  w.i64(BigInt(gameCode(vm)));
  w.i64(gameVer(vm));
  w.str(text);
};
/** user #DIM variables in declaration order */
const userVars = (vm: VM) => [...vm.prog.globals.values()].filter((u) => !u.isConst && !u.isRef);
const mk = (vm: VM, name: string) => vm.store.meta(name.toUpperCase());

function writeExt(w: BW, vm: VM, group: 'save' | 'global', snap: Snap | null) {
  const x = vm.config.varExt;
  const maps = new Map(snap ? snap.maps : [...vm.maps].map(([k, m]) => [k, [...m]] as [string, [string, string][]]));
  const dts = new Map(snap ? snap.dts : [...vm.dts].map(([k, t]) => [k, t.dump()] as [string, any]));
  for (const k of x.maps[group]) {
    const m = maps.get(k);
    if (!m) continue;
    w.u8(DT.Map);
    w.str(k);
    w.i32(m.length);
    for (const [a, b] of m) {
      w.str(a);
      w.str(b);
    }
  }
  const xmls = new Map(
    snap ? (snap.xmls ?? []) : [...vm.xmlDocs].map(([k, d]) => [k, outerXml(d)] as [string, string]),
  );
  for (const k of x.xmls[group]) {
    const t = xmls.get(k);
    if (t !== undefined) {
      w.u8(DT.Xml);
      w.str(k);
      w.str(t);
    }
  }
  for (const k of x.dts[group]) {
    const d = dts.get(k);
    if (!d) continue;
    const t = DataTable.load(d);
    w.u8(DT.DT);
    w.str(k);
    w.str(schemaXml(t, k));
    w.str(dataXml(t, k));
  }
  w.u8(DT.EOF);
}

/** web slot -> saveNN.sav (uncompressed binary; `rec.data` is vm.snapshot(true)) */
export function toNativeSlot(vm: VM, rec: { info: string; data: string }): Uint8Array {
  const d = parseSaveText(rec.data) as Snap;
  const gl = new Map([...(d.statics ?? []), ...d.global].map(([k, a]) => [k, a] as [string, Arr]));
  const w = new BW();
  header(w, FT.Normal, vm, rec.info);
  const uv = userVars(vm);
  const charaUser = uv.filter((u) => u.isChara);
  w.i64(d.charas.length);
  for (const c of d.charas) {
    const cv = new Map(c.vars);
    for (const v of SAVED) {
      if (!v.chara) continue;
      const m = mk(vm, v.name);
      if (!m || !m.chara) continue;
      wVar(w, v.name, m, cv.get(v.name));
    }
    if (charaUser.length) {
      // 1813: #DIM ... CHARADATA variables follow a separator
      w.u8(DT.Separator);
      for (const u of charaUser) {
        if (!u.isSave) continue;
        const m = mk(vm, u.name);
        if (m) wVar(w, u.name, m, cv.get(u.name.toUpperCase()));
      }
    }
    w.u8(DT.EOC);
  }
  for (const v of SAVED) {
    if (v.chara || v.global) continue;
    const m = mk(vm, v.name);
    if (!m || m.chara) continue;
    wVar(w, v.name, m, gl.get(v.name));
  }
  for (const u of uv) {
    if (u.isChara || u.isGlobal || !u.isSave) continue;
    const m = mk(vm, u.name);
    if (m) wVar(w, u.name, m, gl.get(u.name.toUpperCase()));
  }
  w.u8(DT.EOF);
  writeExt(w, vm, 'save', d);
  return w.bytes();
}

/** web global -> global.sav (`rec.data` is saveGlobalText) */
export function toNativeGlobal(vm: VM, rec: { data: string }): Uint8Array {
  const list = parseSaveText(rec.data) as [string, Arr][];
  const gl = new Map(list);
  const w = new BW();
  header(w, FT.Global, vm, '');
  for (const v of SAVED) {
    if (!v.global) continue;
    const m = mk(vm, v.name);
    if (m) wVar(w, v.name, m, gl.get(v.name));
  }
  for (const u of userVars(vm)) {
    if (!u.isGlobal || u.isChara) continue;
    const m = mk(vm, u.name);
    if (m) wVar(w, u.name, m, gl.get(u.name.toUpperCase()));
  }
  w.u8(DT.EOF);
  writeExt(w, vm, 'global', null);
  return w.bytes();
}

// ------------------------------------------------------------------------------------------------ reader
interface Rec {
  type: number;
  key: string;
  dims: number[];
  cells: Value[];
  scalar?: Value;
  map?: [string, string][];
  dtSchema?: string;
  dtData?: string;
  xml?: string;
}
/** one array body: the run-length state machine of ReadIntArray / ReadIntArray2D / ReadIntArray3D (and the string twins), into a saved-shape buffer */
function rArr(r: BR, rank: number, isStr: boolean): { dims: number[]; cells: Value[] } {
  const dims: number[] = [];
  for (let i = 0; i < rank; i++) dims.push(r.i32());
  const total = dims.reduce((p, q) => p * q, 1);
  if (dims.some((d) => d < 0) || !(total <= MAX_CELLS))
    throw new NativeSaveError('array size in the save file is not plausible');
  const empty: Value = isStr ? '' : 0;
  const cells: Value[] = new Array(dims.reduce((p, q) => p * q, 1)).fill(empty);
  const [l0, l1, l2] = [dims[0], dims[1] ?? 1, dims[2] ?? 1];
  let x = 0,
    y = 0,
    z = 0;
  const set = (v: Value) => {
    if (x >= l0 || y >= l1 || z >= l2) throw new NativeSaveError('array data runs past its declared size');
    cells[rank === 1 ? x : rank === 2 ? x * l1 + y : (x * l1 + y) * l2 + z] = v;
  };
  const adv = () => {
    if (rank === 1) x++;
    else if (rank === 2) y++;
    else z++;
  };
  for (;;) {
    const b = r.u8();
    if (b === E.EoD) break;
    if (b === E.Zero) {
      const c = Number(r.int());
      if (rank === 1) x += c;
      else if (rank === 2) y += c;
      else z += c;
      continue;
    }
    if (b === E.ZeroA1 && rank >= 2) {
      const c = Number(r.int());
      if (rank === 2) {
        x += c;
        y = 0;
      } else {
        y += c;
        z = 0;
      }
      continue;
    }
    if (b === E.ZeroA2 && rank === 3) {
      x += Number(r.int());
      y = 0;
      z = 0;
      continue;
    }
    if (b === E.EoA1 && rank >= 2) {
      if (rank === 2) {
        x++;
        y = 0;
      } else {
        y++;
        z = 0;
      }
      continue;
    }
    if (b === E.EoA2 && rank === 3) {
      x++;
      y = 0;
      z = 0;
      continue;
    }
    if (isStr) {
      if (b !== E.String) throw new NativeSaveError('abnormal binary data in the save file');
      set(r.str());
    } else if (b <= E.Byte) set(b);
    else if (b === E.Int16) set(r.i16());
    else if (b === E.Int32) set(r.i32());
    else if (b === E.Int64) set(norm(r.i64()));
    else throw new NativeSaveError('abnormal binary data in the save file');
    adv();
  }
  return { dims, cells };
}
/** one record after its type byte (ReadVariableCode + the matching Read*) */
function rRec(r: BR, type: number): Rec {
  if (type === DT.Map) {
    const key = r.str(),
      n = r.i32(),
      map: [string, string][] = [];
    for (let i = 0; i < n; i++) {
      const k = r.str();
      map.push([k, r.str()]);
    }
    return { type, key, dims: [], cells: [], map };
  }
  if (type === DT.Xml) {
    const key = r.str();
    return { type, key, dims: [], cells: [], xml: r.str() };
  }
  if (type === DT.DT) {
    const key = r.str();
    const s = r.str();
    return { type, key, dims: [], cells: [], dtSchema: s, dtData: r.str() };
  }
  const key = r.str();
  if (type === DT.Int) return { type, key, dims: [], cells: [], scalar: r.int() };
  if (type === DT.Str) return { type, key, dims: [], cells: [], scalar: r.str() };
  if (type === DT.IntArray || type === DT.IntArray2D || type === DT.IntArray3D)
    return { type, key, ...rArr(r, type - DT.IntArray + 1, false) };
  if (type === DT.StrArray || type === DT.StrArray2D || type === DT.StrArray3D)
    return { type, key, ...rArr(r, type - DT.StrArray + 1, true) };
  throw new NativeSaveError('abnormal data in the save file');
}
/** records up to EOF (variables, and EM-block maps / xml / tables) */
function rUntilEof(r: BR): Rec[] {
  const out: Rec[] = [];
  for (;;) {
    const t = r.u8();
    if (t === DT.EOF) return out;
    out.push(rRec(r, t));
  }
}

/** a saved array placed into the current variable's shape: the overlap is copied, the rest is the default (the 1818 fix in the original) */
function fit(rec: Rec, m: Meta): Arr {
  const size = m.dims.reduce((p, q) => p * q, 1);
  const a: Arr = new Array(size).fill(m.isStr ? '' : 0);
  const sd = rec.dims,
    td = m.dims;
  const g = (d: number[], i: number) => d[i] ?? 1;
  for (let x = 0; x < Math.min(g(sd, 0), g(td, 0)); x++)
    for (let y = 0; y < Math.min(g(sd, 1), g(td, 1)); y++)
      for (let z = 0; z < Math.min(g(sd, 2), g(td, 2)); z++) {
        const si = (x * g(sd, 1) + y) * g(sd, 2) + z,
          ti = (x * g(td, 1) + y) * g(td, 2) + z;
        a[ti] = rec.cells[si];
      }
  return a;
}
const typeOk = (rec: Rec, m: Meta) => {
  const str = rec.type >= DT.Str && rec.type <= DT.StrArray3D;
  if (str !== m.isStr) return false;
  const rank = rec.type === DT.Int || rec.type === DT.Str ? 0 : rec.type & 0x0f;
  return rank === m.rank;
};
const place = (rec: Rec, m: Meta): Arr => {
  if (rec.scalar !== undefined) return [rec.scalar];
  return fit(rec, m);
};

async function gunzip(b: Uint8Array): Promise<Uint8Array> {
  const ds = new DecompressionStream('gzip');
  const out = new Response(new Blob([b as BlobPart]).stream().pipeThrough(ds)).arrayBuffer();
  return new Uint8Array(await out);
}

export interface NativeResult {
  kind: 'slot' | 'global';
  info: string;
  code: string;
  ver: number;
  data: string;
  /** save format version found in the file (1808 is the one this code was written for; others are tried anyway) */
  fmt: number;
  characters: number;
  /** variables in the file that this game does not have, or that have another type/rank (their data is not loaded) */
  skipped: string[];
  warnings: string[];
}
/**
 * saveNN.sav / global.sav -> a web record. The game code and version are returned as read; the caller decides whether they match
 * (the original refuses a save of another game or an incompatible version). Variables the game does not have, or whose type or
 * dimension differs, are skipped as the original does.
 */
export async function fromNative(vm: VM, bytes: Uint8Array): Promise<NativeResult> {
  if (bytes.length < 16) throw new NativeSaveError('not an Emuera save file (too short)');
  const hd = (h: number[]) => h.every((v, i) => bytes[i] === v);
  const zipped = hd(ZIP_HEADER);
  if (!hd(HEADER) && !zipped)
    throw new NativeSaveError(
      'not a binary Emuera save file (the header is wrong; text-format saves are not supported)',
    );
  const br0 = new BR(bytes, 8);
  const version = br0.u32();
  const warnings: string[] = [];
  if (version !== VERSION)
    warnings.push(`save format version ${version} (this reader was written for ${VERSION}); trying anyway`);
  const count = br0.u32();
  br0.p += count * 4;
  const r = zipped ? new BR(await gunzip(bytes.subarray(br0.p))) : br0;
  const type = r.u8();
  if (type !== FT.Normal && type !== FT.Global)
    throw new NativeSaveError(
      type === FT.Var || type === FT.CharVar
        ? 'this is a SAVEVAR/SAVECHARA file, not a game save'
        : 'abnormal file type',
    );
  const code = r.i64(),
    ver = Number(r.i64()),
    info = r.str();
  const skipped: string[] = [];
  const snap: any = {
    global: [],
    statics: [],
    charas: [],
    maps: [],
    dts: [],
    xmls: [],
    system: {},
    ver,
    code: String(code),
  };
  const group = type === FT.Global ? 'global' : 'save';
  const uv = userVars(vm);
  const known = new Set<string>([
    ...SAVED.map((v) => v.name.toUpperCase()),
    ...uv.filter((u) => u.isSave || u.isGlobal).map((u) => u.name.toUpperCase()),
  ]);
  const putStatic = (rec: Rec) => {
    const K = rec.key.toUpperCase(),
      m = vm.store.meta(K);
    if (!m || m.chara || !known.has(K) || !typeOk(rec, m)) {
      skipped.push(rec.key);
      return;
    }
    if (
      m.user ? (type === FT.Global) !== !!m.user.isGlobal : (K === 'GLOBAL' || K === 'GLOBALS') !== (type === FT.Global)
    )
      return;
    const arr = place(rec, m);
    if (nonDefault(arr) || (vm.store as any).defaultFor?.(K)) snap.global.push([K, arr]); // sparse like vm.snapshot: untouched variables are omitted
  };
  const putExt = (rec: Rec) => {
    const x = vm.config.varExt;
    if (rec.type === DT.Map && x.maps[group].has(rec.key)) snap.maps.push([rec.key, rec.map]);
    else if (rec.type === DT.DT && x.dts[group].has(rec.key)) {
      const t = dtFromXml(rec.key, rec.dtSchema!, rec.dtData!);
      if (t) snap.dts.push([rec.key, t.dump()]);
    } else if (rec.type === DT.Xml && x.xmls[group].has(rec.key)) snap.xmls.push([rec.key, (rec as any).xml]);
  };
  if (type === FT.Normal) {
    const nChara = Number(r.i64());
    for (let i = 0; i < nChara; i++) {
      const vars: [string, Arr][] = [];
      let userMode = false;
      let noVal: Value | undefined;
      for (;;) {
        const t = r.u8();
        if (t === DT.EOC) break;
        if (t === DT.Separator) {
          userMode = true;
          continue;
        }
        const rec = rRec(r, t),
          K = rec.key.toUpperCase(),
          m = vm.store.meta(K);
        if (!m || !m.chara || !typeOk(rec, m)) {
          if (!skipped.includes(rec.key)) skipped.push(rec.key);
          continue;
        }
        const savedBuiltin = SAVED.some((v) => v.chara && v.name.toUpperCase() === K);
        const savedUser = m.user && m.user.isSave;
        if (userMode ? !savedUser : !savedBuiltin) continue;
        const arr = place(rec, m);
        if (K === 'NO') noVal = arr[0];
        if (nonDefault(arr)) vars.push([K, arr]);
      }
      const no = noVal;
      snap.charas.push({ no: Number(no ?? 0), vars });
    }
  }
  for (const rec of rUntilEof(r)) {
    if (rec.type === DT.Map || rec.type === DT.Xml || rec.type === DT.DT) putExt(rec);
    else putStatic(rec);
  }
  if (!r.eof) for (const rec of rUntilEof(r)) putExt(rec);
  const data = JSON.stringify(type === FT.Global ? snap.global : snap, (_k, v) =>
    typeof v === 'bigint' ? { $b: v.toString() } : v,
  );
  return {
    kind: type === FT.Global ? 'global' : 'slot',
    info,
    code: String(code),
    ver,
    data,
    fmt: version,
    characters: snap.charas.length,
    skipped,
    warnings,
  };
}

/** native file name <-> our slot key: save07.sav <-> save7, global.sav <-> global (the original names slots with at least two digits) */
export const slotKeyOfFile = (name: string): string | null => {
  const base = name.replace(/^.*[\\/]/, '').toLowerCase();
  if (base === 'global.sav') return 'global';
  const m = /^save(\d+)\.sav$/.exec(base);
  return m ? 'save' + Number(m[1]) : null;
};
export const fileOfSlotKey = (key: string): string | null => {
  if (key === 'global') return 'global.sav';
  const m = /^save(\d+)$/.exec(key);
  return m ? `save${m[1].padStart(2, '0')}.sav` : null;
};

